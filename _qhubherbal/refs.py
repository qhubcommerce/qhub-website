def refs_for(body):
    low = body.lower(); out = []
    for key, kws, n in RULES:
        if sum(low.count(k) for k in kws) >= n:
            out += SRC[key]
    seen = set(); res = []
    for t, u in out:
        if u not in seen:
            seen.add(u); res.append((t, u))
    return res[:6]


